"""Alembic environment: wired to the app's configured database.

The URL comes from ``syzygy.database.settings.database_url`` — the same
pydantic-settings value the app uses (``.env`` / ``DATABASE_URL``);
nothing is hard-coded here. ``target_metadata`` is the app's
``Base.metadata`` so ``alembic revision --autogenerate`` diffs against
the live models. Caveat: autogenerate does NOT understand the DMP
``GENERATED ... STORED`` key columns (see ``0001_baseline.py``), so
revisions touching those four columns are hand-written and every
autogenerated diff must be reviewed by hand.

Override for one-off runs: set ``ALEMBIC_DATABASE_URL`` (used by
scripts/alembic_bootstrap.py when passed an explicit URL argument).
"""
import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

from syzygy.database import Base, settings
import syzygy.models  # noqa: F401  (register all tables on Base.metadata)

config = context.config

# Fill in the URL: explicit main option (bootstrap script) > env override
# > the app settings. No hard-coded URL.
if not config.get_main_option("sqlalchemy.url"):
    url = os.environ.get("ALEMBIC_DATABASE_URL") or settings.database_url
    config.set_main_option("sqlalchemy.url", url)

if config.config_file_name is not None:
    # env.py also runs IN-PROCESS (the bootstrap script and
    # tests/test_alembic.py call alembic commands from the same
    # interpreter). fileConfig disables every existing logger that is not
    # in the config file by default (Python 3.14:
    # disable_existing_loggers=True) — which would disable the app's
    # loggers (e.g. syzygy.auth) and break the logging tests that run
    # afterwards. (It also clears existing handlers unconditionally, but
    # pytest's caplog handler is attached per test, so that is harmless.)
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode.

    Configures the context with just a URL and not an Engine;
    calls to context.execute() here emit the given string to the
    script output.
    """
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode.

    Configures the context with an Engine that could be created by
    any of the create_engine() functions.
    """
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
        )

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
